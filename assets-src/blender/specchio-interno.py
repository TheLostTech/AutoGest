A, B = 0.122, 0.034        # half width / half height of the head
NU = 96


def outline(i, s=1.0):
    """Head outline point i (x, z): superellipse with a slightly narrower top edge."""
    t = math.tau * i / NU
    c, sn = math.cos(t), math.sin(t)
    x = A * math.copysign(abs(c) ** (2 / 3.6), c)
    z = B * math.copysign(abs(sn) ** (2 / 3.0), sn)
    x *= 1 - 0.07 * sstep(0.0, B, z)          # top edge shorter
    z += 0.004 * (1 - (x / A) ** 2)            # top slightly arched
    return x * s, z * s


def housing(mat):
    # (scale, y) rings from the bezel lip to the domed back
    P = [(0.962, 0.0015), (0.962, -0.0035), (0.985, -0.0060), (1.0, -0.0040), (1.012, 0.004), (1.0, 0.014),
         (0.94, 0.024), (0.80, 0.032), (0.58, 0.037), (0.30, 0.040)]
    bm = bmesh.new()
    rings = [[bm.verts.new((outline(i, s)[0], y, outline(i, s)[1])) for i in range(NU)] for (s, y) in P]
    for a, b in zip(rings[:-1], rings[1:]):
        for k in range(NU):
            k2 = (k + 1) % NU
            bm.faces.new((a[k], a[k2], b[k2], b[k]))
    bm.faces.new(rings[-1])
    bm.faces.new(rings[0][::-1])
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    ob = C.mesh_obj("Housing", bm, [mat])
    sd = ob.modifiers.new("Sub", "SUBSURF")
    sd.levels = sd.render_levels = 2
    return C.finalize(ob, angle=50)


def glass(mirror_m, edge_m):
    bm = bmesh.new()
    s = 0.958
    ring0 = [bm.verts.new((outline(i, s)[0], -0.0012, outline(i, s)[1])) for i in range(NU)]
    ring1 = [bm.verts.new((outline(i, s)[0], 0.0010, outline(i, s)[1])) for i in range(NU)]
    f = bm.faces.new(ring0[::-1])
    f.material_index = 0
    for k in range(NU):
        k2 = (k + 1) % NU
        bm.faces.new((ring0[k], ring0[k2], ring1[k2], ring1[k])).material_index = 1
    bm.faces.new(ring1).material_index = 1
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    ob = C.mesh_obj("Glass", bm, [mirror_m, edge_m])
    return C.finalize(ob, angle=30)


def flip_tab(mat):
    def shape(p, u, v, w):
        p.y -= 0.004 * (w + 1) / 2 * (v < 0)
        return p
    return box_soft("FlipTab", [mat], (-0.013, -0.006, -B - 0.012), (0.013, 0.010, -B + 0.004), n=(3, 2, 2), levels=2,
                    shape=shape)


def stem_and_foot(mat, dark, spring_m):
    out = []
    ball = Vector((0.0, 0.046, 0.012))
    # boss on the back of the housing holding the ball socket
    bo = C.lathe("Boss", [(0.0, 0.0, 0), (0.016, 0.0, 0), (0.015, 0.008, 0), (0.011, 0.014, 0), (0.0, 0.014, 0)],
                 [mat], steps=40)
    bo.matrix_world = Matrix.Translation((0, 0.030, 0.010)) @ Matrix.Rotation(math.radians(-90), 4, "X")
    out.append(C.finalize(bo, angle=40))
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=32, v_segments=16, radius=0.0105,
                              matrix=Matrix.Translation(ball))
    sp = C.mesh_obj("Ball", bm, [mat])
    out.append(C.finalize(sp, angle=60))
    # stem rising to the foot
    top = Vector((0.0, 0.074, 0.060))
    out.append(tube("Stem", [ball, ball.lerp(top, 0.5) + Vector((0, -0.002, 0.003)), top], 0.0068, mat, res=4))
    # windscreen foot: pad bonded to the glass, tilted with the screen (~28 deg from horizontal)
    ang = math.radians(-28)
    Mf = Matrix.Translation(top + Vector((0, 0.010, 0.012))) @ Matrix.Rotation(ang, 4, "X")

    def shroud_shape(p, u, v, w):
        p.x *= 1 - 0.18 * (1 - (w + 1) / 2)
        return p
    out.append(box_soft("FootShroud", [mat], (-0.017, -0.026, -0.010), (0.017, 0.026, 0.010), n=(3, 4, 2), levels=2,
                        shape=shroud_shape, M=Mf))
    # bonded metal button (dark) on top of the shroud
    bt = C.lathe("Button", [(0.0, 0.0, 0), (0.0125, 0.0, 0), (0.0125, 0.003, 0), (0.0105, 0.0045, 0), (0.0, 0.0045, 0)],
                 [dark], steps=40)
    bt.matrix_world = Mf @ Matrix.Translation((0, 0.004, 0.0095))
    out.append(C.finalize(bt, angle=40))
    # locking spring clip across the shroud
    pts = [Mf @ Vector((x, -0.015, z)) for (x, z) in ((-0.019, -0.004), (-0.019, 0.010), (0.019, 0.010), (0.019, -0.004))]
    out.append(tube("SpringClip", pts, 0.0011, spring_m, res=2))
    return out


