"""Diesel glow plugs (candelette), a matched pair as removed from the head: thin
heat-tinted sheathed heater tip, conical sealing seat, long zinc-plated shank, M10
thread, hex, insulating ring, threaded terminal stud with knurled round nut.

Each plug built along local Z (tip at z=0). 1 unit = 100 mm."""
import sys, os
